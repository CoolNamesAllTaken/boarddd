# TypeScript


def _ts(tp: Any) -> str:
    optional, tp = _is_optional(tp)
    t = _ts_inner(tp)
    return f"{t} | null" if optional else t


def _ts_inner(tp: Any) -> str:
    origin, args = get_origin(tp), get_args(tp)
    if tp is str:
        return "string"
    if tp is bool:
        return "boolean"
    if tp in (int, float):
        return "number"
    if tp is Any:
        return "unknown"
    if origin is Literal:
        return " | ".join(json.dumps(a) for a in args)
    if origin is list:
        inner = _ts(args[0])
        return f"({inner})[]" if "|" in inner else f"{inner}[]"
    if origin is tuple:
        if all(a is float for a in args) and len(args) in (2, 3):
            return f"Vec{len(args)}"
        return "[" + ", ".join(_ts(a) for a in args) + "]"
    if origin is dict:
        return f"Record<string, {_ts(args[1])}>"
    if is_dataclass(tp):
        return tp.__name__
    raise TypeError(f"unsupported type {tp!r}")


def _classes(root: type = model.Board) -> list[type]:
    seen: list[type] = []

    def walk(tp: Any) -> None:
        for a in get_args(tp):
            walk(a)
        if is_dataclass(tp) and tp not in seen:
            seen.append(tp)
            for f in fields(tp):
                walk(model._hints(tp)[f.name])

    walk(root)
    return seen


def dts() -> str:
    out = [f"// {HEADER}", "// The boarddd/board@1 model; see docs/model.md.", ""]
    out.append(f"export type SchemaId = {json.dumps(model.SCHEMA_ID)};")
    out.append("/** x, y in mm. */")
    out.append("export type Vec2 = [number, number];")
    out.append("export type Vec3 = [number, number, number];")
    out.append("")
    _interfaces(out, _classes())
    return "\n".join(out)


def copper_dts() -> str:
    """src/copper/copper.d.ts: the copper@1 interfaces; the ones board@1 has too are imported from it."""
    return _sub_dts(copper.Copper, COPPER_HEADER, "The boarddd/copper@1 model; see docs/copper.md.", "CopperSchemaId")


def impedance_dts() -> str:
    """src/impedance/result.d.ts: the impedance@1 interfaces (board@1's Vec2 imported)."""
    return _sub_dts(
        impedance_result.ImpedanceAnalysis,
        IMPEDANCE_HEADER,
        "The boarddd/impedance@1 result document; see docs/impedance.md.",
        "ImpedanceSchemaId",
    )


def _sub_dts(root: type, header: str, what: str, id_name: str) -> str:
    board = set(_classes())
    own = [c for c in _classes(root) if c not in board]
    shared = sorted(c.__name__ for c in _classes(root) if c in board)
    out = [f"// {header}", f"// {what}", ""]
    out.append(f"import type {{ {', '.join([*shared, 'Vec2'])} }} from '../model/board.js';")
    out.append(f"export type {{ {', '.join([*shared, 'Vec2'])} }};")
    out.append("")
    out.append(f"export type {id_name} = {json.dumps(ROOTS[root][0])};")
    out.append("")
    _interfaces(out, own)
    return "\n".join(out)


def _interfaces(out: list[str], classes: list[type]) -> None:
    for cls in classes:
        out.append(f"/** {_desc(cls)} */")
        out.append(f"export interface {cls.__name__} {{")
        hints = model._hints(cls)
        for f in fields(cls):
            must = f.metadata.get("schema", {}).get("required", False)
            opt = "?" if not must and (f.default is not MISSING or f.default_factory is not MISSING) else ""
            text = f.metadata.get("doc")
            if text:
                out.append(f"  /** {text} */")
            out.append(f"  {f.name}{opt}: {_ts(hints[f.name])};")
        out.append("}")
        out.append("")


def schema_js(text: str, header: str = HEADER, rel: str = "schema/board.schema.json") -> str:
    return f"// {header}\n// The same object as {rel}, as an ES module (no JSON imports needed).\nexport default {text.rstrip()};\n"


def outputs() -> dict[str, str]:
    text = json.dumps(schema(), indent=2, ensure_ascii=False) + "\n"
    ctext = json.dumps(schema(copper.Copper), indent=2, ensure_ascii=False) + "\n"
    itext = json.dumps(schema(impedance_result.ImpedanceAnalysis), indent=2, ensure_ascii=False) + "\n"
    return {
        "schema/board.schema.json": text,
        "src/model/schema.js": schema_js(text),
        "src/model/board.d.ts": dts(),
        "schema/copper.schema.json": ctext,
        "src/copper/schema.js": schema_js(ctext, COPPER_HEADER, "schema/copper.schema.json"),
        "src/copper/copper.d.ts": copper_dts(),
        "schema/impedance.schema.json": itext,
        "src/impedance/schema.js": schema_js(itext, IMPEDANCE_HEADER, "schema/impedance.schema.json"),
        "src/impedance/result.d.ts": impedance_dts(),
    }
