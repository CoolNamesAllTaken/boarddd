"""Generate the JSON Schemas and JS typings from the dataclasses: schema/board.schema.json, src/model/schema.js
and src/model/board.d.ts from boarddd.model; schema/copper.schema.json, src/copper/schema.js and
src/copper/copper.d.ts from boarddd.copper.

The schema uses a small JSON Schema 2020-12 subset that both hand-written validators (Python
boarddd.validate, JS src/model/index.js) implement: type, const, enum, properties, required,
additionalProperties, items, prefixItems, minItems, maxItems, minimum, maximum, exclusiveMinimum,
pattern, anyOf, $ref (#/$defs/...).
"""

from __future__ import annotations

import json
import types
from dataclasses import MISSING, fields, is_dataclass
from pathlib import Path
from typing import Any, Literal, Union, get_args, get_origin

from . import copper, model
from .impedance import result as impedance_result

HEADER = "Generated by `python -m boarddd.model --write` from python/src/boarddd/model.py. Do not edit."
COPPER_HEADER = "Generated by `python -m boarddd.model --write` from python/src/boarddd/copper.py. Do not edit."
IMPEDANCE_HEADER = (
    "Generated by `python -m boarddd.model --write` from python/src/boarddd/impedance/result.py. Do not edit."
)
#: root class -> ($id, $comment, title)
ROOTS = {
    model.Board: (model.SCHEMA_ID, HEADER, "boarddd board model"),
    copper.Copper: (copper.SCHEMA_ID, COPPER_HEADER, "boarddd copper model"),
    impedance_result.ImpedanceAnalysis: (impedance_result.SCHEMA_ID, IMPEDANCE_HEADER, "boarddd impedance analysis"),
}


def repo_root() -> Path:
    return Path(__file__).resolve().parents[3]


def _is_optional(tp: Any) -> tuple[bool, Any]:
    origin, args = get_origin(tp), get_args(tp)
    if (origin is Union or origin is types.UnionType) and type(None) in args:
        rest = [a for a in args if a is not type(None)]
        return True, rest[0] if len(rest) == 1 else Union[tuple(rest)]  # noqa: UP007
    return False, tp


def _desc(cls: type) -> str:
    return " ".join((cls.__doc__ or "").split())


class _Gen:
    def __init__(self) -> None:
        self.defs: dict[str, Any] = {}

    def type_schema(self, tp: Any) -> dict[str, Any]:
        optional, tp = _is_optional(tp)
        s = self._schema(tp)
        if not optional:
            return s
        if set(s) <= {"type", "enum"} and isinstance(s.get("type"), str):
            s = dict(s, type=[s["type"], "null"])
            if "enum" in s:
                s["enum"] = [*s["enum"], None]
            return s
        return {"anyOf": [s, {"type": "null"}]}

    def _schema(self, tp: Any) -> dict[str, Any]:
        origin, args = get_origin(tp), get_args(tp)
        if tp is str:
            return {"type": "string"}
        if tp is bool:
            return {"type": "boolean"}
        if tp is int:
            return {"type": "integer"}
        if tp is float:
            return {"type": "number"}
        if tp is Any:
            return {}
        if origin is Literal:
            if len(args) == 1:
                return {"const": args[0]}
            return {"type": "string", "enum": list(args)}
        if origin is list:
            return {"type": "array", "items": self.type_schema(args[0])}
        if origin is tuple:
            return {
                "type": "array",
                "prefixItems": [self.type_schema(a) for a in args],
                "items": False,
                "minItems": len(args),
                "maxItems": len(args),
            }
        if origin is dict:
            return {"type": "object", "additionalProperties": self.type_schema(args[1])}
        if is_dataclass(tp):
            self.define(tp)
            return {"$ref": f"#/$defs/{tp.__name__}"}
        raise TypeError(f"unsupported type {tp!r}")

    def define(self, cls: type) -> dict[str, Any]:
        if cls.__name__ in self.defs:
            return self.defs[cls.__name__]
        obj: dict[str, Any] = {"type": "object", "description": _desc(cls)}
        self.defs[cls.__name__] = obj  # before recursing (no cycles today, but cheap)
        hints = model._hints(cls)
        props: dict[str, Any] = {}
        required = []
        for f in fields(cls):
            s = self.type_schema(hints[f.name])
            extra = dict(f.metadata.get("schema", {}))
            must = extra.pop("required", False)  # has a Python default but documents must state it
            item_extra = extra.pop("items", None)
            if item_extra:
                s = dict(s, items=dict(s["items"], **item_extra))
            if extra:
                target = s["anyOf"][0] if "anyOf" in s else s
                target.update(extra)
            if f.metadata.get("doc"):
                s = {"description": f.metadata["doc"], **s}
            if must:
                required.append(f.name)
            elif f.default is not MISSING:
                s["default"] = model.to_dict(f.default)
            elif f.default_factory is not MISSING:
                s["default"] = model.to_dict(f.default_factory())
            else:
                required.append(f.name)
            props[f.name] = s
        obj["properties"] = props
        obj["required"] = required
        obj["additionalProperties"] = False
        return obj


def schema(root_cls: type = model.Board) -> dict[str, Any]:
    """The JSON Schema of a root class in ROOTS (board@1, copper@1, impedance@1)."""
    g = _Gen()
    root = g.define(root_cls)
    defs = {k: v for k, v in g.defs.items() if k != root_cls.__name__}
    sid, comment, title = ROOTS[root_cls]
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": sid,
        "$comment": comment,
        "title": title,
        **root,
        "$defs": dict(sorted(defs.items())),
    }


